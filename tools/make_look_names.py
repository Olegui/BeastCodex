"""Writes Locales/LookNames.lua from per-language JSON files.

    py tools/make_look_names.py <dir with looks_<locale>.json>

The appearance names ("looks") come from Petopia in English and the game has
no translation for them, so they are translated by hand: one JSON object per
language, English name -> translation. Every language must cover every look
in Data/Creatures.lua; esMX reuses esES when it has no file of its own.
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from tools.huntmaster import read_lua_tables  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCALES = ("deDE", "esES", "esMX", "frFR", "itIT", "koKR", "ptBR", "ruRU", "zhCN", "zhTW")


def lua_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def main(src):
    with open(os.path.join(ROOT, "Data", "Creatures.lua"), encoding="utf-8") as f:
        names = sorted({v["name"] for v in read_lua_tables(f.read())["Looks"].values()})
    lines = ["-- GENERATED by tools/make_look_names.py. Do not edit by hand.",
             "-- Appearance names (from Petopia, English) translated per client language.",
             "-- Hand translations, not reviewed by native speakers except ptBR.",
             "local ADDON, ns = ...", "",
             "local all = {"]
    problems = []
    for loc in LOCALES:
        path = os.path.join(src, "looks_%s.json" % loc)
        if loc == "esMX" and not os.path.exists(path):
            path = os.path.join(src, "looks_esES.json")
        with open(path, encoding="utf-8") as f:
            table = json.load(f)
        missing = [n for n in names if not str(table.get(n, "")).strip()]
        extra = sorted(set(table) - set(names))
        problems += ["%s: missing %s" % (loc, n) for n in missing] + ["%s: unknown %s" % (loc, n) for n in extra]
        lines.append("  %s = {" % loc)
        for n in names:
            if n in table and str(table[n]).strip():
                lines.append("    [%s] = %s," % (lua_str(n), lua_str(table[n].strip())))
        lines.append("  },")
    lines += ["}", "", "-- Only the client's language is kept.", "ns.LookNames = all[GetLocale()] or {}", ""]
    if problems:
        print("\n".join(problems))
        return 1
    with open(os.path.join(ROOT, "Locales", "LookNames.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote Locales/LookNames.lua: %d looks x %d languages" % (len(names), len(LOCALES)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
